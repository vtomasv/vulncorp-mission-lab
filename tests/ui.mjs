// Verificación de desarrollo opcional. Los alumnos no necesitan Node ni Playwright.
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const {chromium}=await import(process.env.PLAYWRIGHT_PATH||'playwright');
const browser=await chromium.launch({headless:true,...(process.env.PLAYWRIGHT_CHANNEL?{channel:process.env.PLAYWRIGHT_CHANNEL}:{})});
const page=await browser.newPage({viewport:{width:1440,height:1060},deviceScaleFactor:1});
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
await page.goto('http://127.0.0.1:8095');
await page.getByRole('heading',{name:/No puedes proteger/}).waitFor();
await page.getByText('3/3 TARGETS EN LÍNEA',{exact:false}).waitFor();
await fs.mkdir('docs/assets',{recursive:true});
await page.screenshot({path:'docs/assets/mission-control.png',fullPage:true});
await page.getByRole('button',{name:'Probar exportación',exact:true}).click();
await page.getByRole('status').filter({hasText:'Evidencia'}).waitFor();
await page.getByRole('button',{name:/Misiones/}).click();
await page.getByRole('heading',{name:/Tres clases/}).waitFor();
await page.locator('[data-note="1-1"]').fill('Observé una transacción completada y debo distinguir función de seguridad.');
await page.locator('[data-action="note"][data-id="1-1"]').click();
await page.getByRole('status').filter({hasText:'Reflexión guardada'}).waitFor();
await page.getByRole('button',{name:'Decisiones',exact:false}).first().click();
await page.locator('[data-action="decide"][data-id="F-02"]').click();
const dialog=page.getByRole('dialog');
await dialog.locator('select[name="likelihood"]').selectOption('4');
for (const [key,value] of Object.entries({operation:'4',people:'3',data:'4',financial:'3'}))await dialog.locator(`[name="impact_${key}"]`).selectOption(value);
for(const [key,value] of Object.entries({exploitation:'P',exposure:'O',automatable:'Y',human_impact:'H'}))await dialog.locator(`[name="${key}"]`).selectOption(value);
await dialog.locator('[name="evidence_ids"]').selectOption('EV-EXPORT');
await dialog.locator('[name="reason"]').fill('La evidencia muestra acceso indebido a expedientes; debo preservar la función del cliente y consultar al dueño.');
assert.equal(await dialog.locator('#risk-preview').textContent(),'64');
await dialog.getByRole('button',{name:/Guardar decisión/}).click();
await page.getByRole('status').filter({hasText:'Decisión calculada'}).waitFor();
await page.selectOption('#client-select','agua');
await page.getByRole('button',{name:/Hallazgos/}).click();
await page.getByRole('heading',{name:'Siete entradas no son siete riesgos.'}).waitFor();
await page.getByRole('button',{name:/IA local/}).click();
await page.getByRole('heading',{name:/Una segunda mirada/}).waitFor();
await page.getByRole('button',{name:/Evidencias/}).click();
await page.getByRole('heading',{name:'Una afirmación merece una prueba.'}).waitFor();
await page.setViewportSize({width:390,height:844});
await page.getByRole('button',{name:/Mapa operativo/}).click();
await page.getByRole('heading',{name:/No puedes proteger/}).waitFor();
assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2),'No debe existir scroll horizontal global en móvil.');
await page.screenshot({path:'artifacts/mobile-ui.png',fullPage:true});
assert.deepEqual(errors,[]);
await browser.close();
console.log('PASS: navegación, evidencia, reflexión, decisión, cambio de cliente, IA, escritorio/móvil y consola sin errores.');

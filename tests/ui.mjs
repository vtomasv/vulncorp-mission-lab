const observed=await page.evaluate(async()=>{
 const post=async(path,data)=>{const r=await fetch(path,{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(data)});return r.json();};
 try{return {denied:await post('/api/probe',{action:'export'}),business:await post('/api/probe',{action:'transaction'})};}
 finally{await post('/api/control',{action:'reset',reason:'Fin de prueba de interfaz. Restablecer estado inicial preservando evidencia.'});}
});
assert.equal(observed.denied.result.status,403);
assert.equal(observed.business.result.body.status,'completed');
